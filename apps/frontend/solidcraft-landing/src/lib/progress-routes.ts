export type ProgressKind = "overview" | "units" | "issues" | "ssi" | "unit";
export interface ProgressPage {
	path: string;
	kind: ProgressKind;
	heading: string;
	unit?: string;
}
export const progressPages: ProgressPage[] = [
	{ path: progressBase, kind: "overview", heading: "SolidCore progress." },
	{ path: `${progressBase}units/`, kind: "units", heading: "Units" },
	{
		path: `${progressBase}issues/`,
		kind: "issues",
		heading: "Upstream issues",
	},
	{ path: `${progressBase}ssi/`, kind: "ssi", heading: "SSI corpus" },
	{ path: `${progressBase}unit/`, kind: "unit", heading: "Unit report" },
	...progressUnits.map((unit) => ({
		path: `${progressBase}units/${unit}/`,
		kind: "unit" as const,
		heading: unit,
		unit,
	})),
];
export const progressRedirects = progressPages
	.filter((page) => page.path !== `${progressBase}unit/`)
	.map((page) => ({
		from:
			page.path === progressBase || page.path === `${progressBase}units/`
				? `${page.path}index.html`
				: `${page.path.slice(0, -1)}.html`,
		to: page.path,
	}));
export const validUnit = (id: string) =>
	/^[a-z0-9_]+(?:[.-][a-z0-9_]+)+$/i.test(id) && id.length < 160;
export function upstreamProgressUrl(page: ProgressPage, dynamicUnit?: string) {
	if (page.kind === "overview") return progressOrigin;
	if (page.kind === "units") return `${progressOrigin}units/`;
	if (page.kind === "unit") {
		const unit = page.unit || dynamicUnit || "";
		if (!validUnit(unit))
			throw new Error("Choose a valid unit from the units list.");
		return `${progressOrigin}units/${unit}.html`;
	}
	return `${progressOrigin + page.kind}.html`;
}
